#!/usr/bin/env python3
"""Build / refresh the singing-shot review page review/sing_v4/ (index.html + <ID>.mp4 + <ID>_mix.m4a + <ID>_vocal.m4a).

    sing_page_v4.py                 cut whatever is missing or older than its comp, rebuild the SHOTS array in index.html
    sing_page_v4.py --refresh F1    comp of F1 changed: re-run the mouth audit for F1, re-cut its picture and sound, rebuild the array
                                    (several ids allowed; the audit needs mediapipe, it re-execs itself, see sing_onset_v4.py)
    sing_page_v4.py --page-only     only rebuild the array from work/review/sing_v4/audit.tsv
Sound windows: each starts 1.0 s before the shot's first frame and ends 1.0 s after its last (mix_v3.wav, vocals_v4.wav).
Shot table (song time of frame 0, own start for spliced parts) lives in tools/review/sing_onset_v4.py SHOTS.
To add a shot: add its line to SHOTS there, run this script.  To change what the page shows for one shot only, edit its line in the
SHOTS array at the top of the <script> in review/sing_v4/index.html (the lines between the BEGIN/END markers are regenerated).
"""
import csv, json, os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import sing_onset_v4 as A  # noqa: E402
PAGE = os.path.join(ROOT, "review/sing_v4"); WORK = os.path.join(ROOT, "work/review/sing_v4")
MIX = os.path.join(ROOT, "media/sound/mix_v3.wav"); VOC = os.path.join(ROOT, "work/stems/vocals_v4.wav")
PAD = 1.0
RANK = {"FAIL": 0, "SUSPECT": 1, "NOT MEASURABLE": 2, "MISSING": 0, "OK": 3}


def sh(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit("failed: %s\n%s" % (" ".join(cmd), r.stderr[-800:]))


def nframes(p):
    o = subprocess.run(["ffprobe", "-v", "error", "-count_frames", "-select_streams", "v", "-show_entries", "stream=nb_read_frames", "-of", "csv=p=0", p], capture_output=True, text=True).stdout
    return int(o.strip().split(",")[0])


def cut(sid, force):
    src = os.path.join(ROOT, "media/comp", sid + ".mp4")
    if not os.path.exists(src):
        return None
    out = {k: os.path.join(PAGE, sid + s) for k, s in (("v", ".mp4"), ("m", "_mix.m4a"), ("o", "_vocal.m4a"))}
    n = nframes(src); t0 = A.SHOTS[sid]["t0"]; dur = n / 24 + 2 * PAD
    if force or not os.path.exists(out["v"]) or os.path.getmtime(out["v"]) < os.path.getmtime(src):
        sh(["ffmpeg", "-v", "error", "-y", "-i", src, "-an", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "medium", "-r", "24", "-movflags", "+faststart", out["v"]])
    for k, wav in (("m", MIX), ("o", VOC)):
        if force or not os.path.exists(out[k]) or os.path.getmtime(out[k]) < os.path.getmtime(src) or os.path.getmtime(out[k]) < os.path.getmtime(wav):
            sh(["ffmpeg", "-v", "error", "-y", "-ss", "%.4f" % (t0 - PAD), "-t", "%.4f" % dur, "-i", wav, "-vn", "-c:a", "aac", "-b:a", "160k", out[k]])
    return n


def build_array():
    rows = {r["shot"]: r for r in csv.DictReader(open(os.path.join(WORK, "audit.tsv")), delimiter="\t")}
    items = []
    for sid in A.ORDER:
        if sid not in rows or not os.path.exists(os.path.join(PAGE, sid + ".mp4")):
            continue
        r = rows[sid]; cfg = A.SHOTS[sid]
        sj = os.path.join(WORK, sid + "_series.json")
        words = [dict(w=w["w"], on=w["on"], end=w["end"]) for w in json.load(open(sj))["words"]] if os.path.exists(sj) else []
        n = nframes(os.path.join(PAGE, sid + ".mp4"))
        items.append(dict(id=sid, who=cfg["who"], file=sid + ".mp4", mix=sid + "_mix.m4a", vocal=sid + "_vocal.m4a", frames=n,
                          t0=round(cfg["t0"], 3), flag=r["flag"], reason=r["reason"], note=cfg.get("note", ""), words=words))
    items.sort(key=lambda x: (RANK.get(x["flag"], 9), A.ORDER.index(x["id"])))
    return items


def write_page(items):
    p = os.path.join(PAGE, "index.html"); s = open(p).read()
    a = s.index("// SHOTS-BEGIN"); b = s.index("// SHOTS-END")
    body = "// SHOTS-BEGIN (regenerated by tools/review/sing_page_v4.py; one shot per line, edit a line to change that shot)\nconst SHOTS = [\n"
    body += ",\n".join("  " + json.dumps(i, ensure_ascii=False) for i in items) + "\n];\n"
    open(p, "w").write(s[:a] + body + s[b:])


def main():
    a = sys.argv[1:]
    os.makedirs(PAGE, exist_ok=True)
    refresh = []
    if "--refresh" in a:
        refresh = [x for x in a if not x.startswith("--")]
        if not refresh: raise SystemExit("--refresh needs a shot id")
    ids = refresh or A.ORDER
    if "--page-only" not in a:
        if refresh:
            sh([sys.executable, os.path.join(HERE, "sing_onset_v4.py")] + refresh)
        for sid in ids:
            if sid not in A.SHOTS: raise SystemExit("unknown shot " + sid)
            n = cut(sid, force=bool(refresh))
            print("%-4s %s" % (sid, "%d frames cut" % n if n else "MISSING comp"), flush=True)
    items = build_array(); write_page(items)
    print("page: %d shots -> %s/index.html" % (len(items), PAGE))


if __name__ == "__main__":
    main()
