def s_egg(rng):
    """Egg tremble: a stone egg rocking on paper: a fast stone-on-paper rattle (grains every 25-45 ms) with a few hairline ticks."""
    d = 1.5
    n = N(d)
    y = np.zeros(n)
    i = 0
    while i < n - N(0.05):
        m = N(0.03)
        tg = np.arange(m) / SR
        y[i:i + m] += lp(white(m, rng), 2500, 2) * np.exp(-tg / 0.004) * rng.uniform(0.3, 1.0)
        i += N(rng.uniform(0.025, 0.045))
    t = np.arange(n) / SR
    y *= np.minimum(t / 0.4, 1) * np.minimum((d - t) / 0.2, 1)
    for tc in (0.55, 0.9, 1.2):
        k = N(tc)
        m = N(0.01)
        y[k:k + m] += bp(white(m, rng), 3000, 9000, 2) * 2
    return norm(pan(y, -0.1), db2a(-3)), "synth: rattle of LP 2.5 kHz noise grains every 25-45 ms (tau 4 ms), crescendo 0.4 s, plus three hairline crack ticks (BP 3-9 kHz) at 0.55/0.9/1.2 s; 1.5 s"


