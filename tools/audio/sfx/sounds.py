def s_neon_hum(rng):
    """Neon-sign transformer hum tuned to D: D2 harmonic series without the 5th/7th/9th/10th partials (F#, C-, E), so it sits
    inside D minor pentatonic (D, A, D, A, D...), slow flutter, faint 2x-line sizzle. 12 s, loop-safe (whole periods)."""
    d = 12.0
    t = tt(d)
    f0 = D2
    parts = {1: 1.0, 2: 0.8, 3: 0.35, 4: 0.45, 6: 0.22, 8: 0.12, 12: 0.06, 16: 0.03}
    y = np.zeros_like(t)
    for k, a in parts.items():
        ph = rng.uniform(0, 2 * np.pi)
        y += a * np.sin(2 * np.pi * f0 * k * t + ph)
    flutter = 1 + 0.06 * np.sin(2 * np.pi * 0.5 * t) + 0.03 * np.sin(2 * np.pi * 1.0 * t + 1.0)   # 0.5 Hz: loops in 12 s
    y *= flutter
    sizzle = bp(white(len(t), rng), 2500, 6000, 2) * (0.5 + 0.5 * np.sin(2 * np.pi * 2 * f0 * t)) ** 4 * 0.05
    y = y + sizzle
    y = np.stack([y, np.roll(y, 37)])        # tiny decorrelation
    return norm(y, db2a(-6)), "synth: D2 (73.4 Hz) harmonic series 1,2,3,4,6,8,12,16 (no F#/E partials: D minor pentatonic), 0.5/1 Hz flutter, faint 2.5-6 kHz sizzle gated at 2x f0; 12 s loop"


def s_relay_tick(rng):
    """Ballast relay / switch tick: a 2 ms metallic click (BP 2-7 kHz), a 6 ms low thunk (LP 600 Hz) and a tiny 1.4 kHz ring."""
    n = N(0.30)
    t = np.arange(n) / SR
    click = bp(white(n, rng), 2000, 7000, 2) * np.exp(-t / 0.0018)
    thunk = lp(white(n, rng), 600, 2) * np.exp(-t / 0.006) * 2.5
    ring = np.sin(2 * np.pi * 1397 * t) * np.exp(-t / 0.035) * 0.08          # F6 (D minor pentatonic)
    y = click + thunk + ring
    return norm(pan(y, 0.0), db2a(-1)), "synth: BP 2-7 kHz noise click (tau 1.8 ms) + LP 600 Hz thunk (tau 6 ms) + faint F6 ring (tau 35 ms)"


def s_room(rng, d, lo, hi, tilt, creaks=0, seed_note=""):
    n = N(d)
    y = np.stack([pink(n, rng), pink(n, rng)])
    y = lp(hp(y, lo, 2), hi, 2)
    y = peq(y, tilt[0], tilt[1], 0.7)
    y = narrow(y, 0.6)
    t = np.arange(n) / SR
    y *= 1 + 0.12 * np.sin(2 * np.pi * 0.07 * t)
    for _ in range(creaks):
        i = rng.integers(N(1), n - N(1))
        m = N(0.18)
        tc = np.arange(m) / SR
        cr = bp(white(m, rng), 500, 1800, 2) * np.exp(-tc / 0.05) * (1 + 0.6 * np.sin(2 * np.pi * 37 * tc)) * 4
        y[:, i:i + m] += pan(cr, rng.uniform(-0.6, 0.6))
    return norm(y, db2a(-6))


