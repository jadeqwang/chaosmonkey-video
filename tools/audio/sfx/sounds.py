def build(name):
    if name in GEN_SOURCES:
        y, how = build_gen(name)
        kind = "generated"
    else:
        rng = np.random.default_rng(abs(hash(name)) % (2 ** 32) if False else sum(map(ord, name)) * 7919)
        y, how = SYNTH[name](rng)
        kind = "synthesised"
    y = stereo(y).astype(np.float32)
    path = os.path.join(OUT, name + ".wav")
    sf.write(path, y.T, SR, subtype="FLOAT")
    with open(os.path.join(OUT, name + ".txt"), "w") as f:
        f.write(f"{name}.wav: {kind}\n{how}\nlength {y.shape[1] / SR:.3f} s, 48 kHz stereo float32. Built by tools/audio/sfx/sounds.py.\n")
    return path


