def s_dab(rng):
    """Rubbing pad / face-paint dab: a soft cloth-on-paper pat, 40 ms body + a paper tick. Four takes back to back (0, .25, .5, .75 s)."""
    out = np.zeros(N(1.0))
    for j in range(4):
        n = N(0.12)
        t = np.arange(n) / SR
        body = lp(white(n, rng), rng.uniform(900, 1400), 2) * np.exp(-t / 0.012)
        tick = bp(white(n, rng), 2500, 7000, 2) * np.exp(-t / 0.0015) * 0.3
        out[N(0.25 * j):N(0.25 * j) + n] += body + tick
    return norm(pan(out, 0.0), db2a(-3)), "synth: four soft dabs at 0/.25/.5/.75 s: LP 0.9-1.4 kHz noise pat (tau 12 ms) + BP 2.5-7 kHz paper tick (tau 1.5 ms)"


def s_flip(rng):
    """Paper flip: a short sheet flicked over, 70 ms crinkle + flap. Four takes at 0/.25/.5/.75 s."""
    out = np.zeros(N(1.0))
    for j in range(4):
        n = N(0.09)
        t = np.arange(n) / SR
        cr = hp(white(n, rng), 1800, 2) * (rng.random(n) < 0.08) * 3
        flap = bp(white(n, rng), 400, 2500, 2) * np.sin(np.pi * t / 0.09) ** 2
        out[N(0.25 * j):N(0.25 * j) + n] += lp(cr * np.exp(-t / 0.03) + flap, 9000, 2)
    return norm(pan(out, 0.0), db2a(-3)), "synth: four paper flips at 0/.25/.5/.75 s: sparse HP 1.8 kHz crinkle grains + BP 0.4-2.5 kHz flap (90 ms)"


def s_brush_wet(rng):
    """One wet ink stroke on xuan paper, 0.5 s: soft bristle drag (BP 600-3500 Hz) with grain, swelling then lifting off."""
    d = 0.5
    n = N(d)
    t = np.arange(n) / SR
    x = t / d
    w = white(n, rng)
    drag = bp(w, 600, 3500, 2) * (1 + 0.5 * (rng.random(n) < 0.02))
    env = (np.minimum(x / 0.08, 1)) * (1 - x) ** 0.6 * (0.6 + 0.4 * np.sin(np.pi * x))
    wet = lp(white(n, rng), 500, 2) * np.exp(-t / 0.03) * 0.6
    y = peq(drag * env + wet, 2600, -3, 1)
    return norm(pan(y, np.linspace(-0.2, 0.2, n)), db2a(-3)), "synth: wet brush stroke: BP 600-3500 Hz bristle drag with sparse grain, 80 ms press, lift-off taper, LP 500 Hz wet touch at the start, -3 dB at 2.6 kHz; 0.5 s, L -> R"


