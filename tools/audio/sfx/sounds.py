def gate(y, thr_db=-38.0, hold=0.08, rel=0.05):
    """Downward gate against the take's own peak: keeps events, drops the floor between them (smooth 5 ms / rel)."""
    m = np.abs(stereo(y)).max(0)
    w = N(0.005)
    env = np.sqrt(np.convolve(m ** 2, np.ones(w) / w, "same"))
    lvl = 20 * np.log10(env + 1e-12) - 20 * np.log10(env.max() + 1e-12)
    g = (lvl > thr_db).astype(float)
    from scipy.ndimage import maximum_filter1d, uniform_filter1d
    g = maximum_filter1d(g, N(hold) * 2 + 1)
    g = uniform_filter1d(g, N(rel))
    return stereo(y) * g


def repitch(y, ratio):
    """Varispeed (pitch and time together) by ratio (2 = octave up)."""
    from fractions import Fraction
    fr = Fraction(1 / ratio).limit_denominator(200)
    return resample_poly(stereo(y), fr.numerator, fr.denominator, axis=-1)


