def _formant_noise(rng, n, formants, bw=0.25):
    y = np.zeros(n)
    w = white(n, rng)
    for f, a in formants:
        y += a * bp(w, f * (1 - bw), f * (1 + bw), 2)
    return y


def s_breath(rng):
    """Mama blows on the page: one long soft out-breath, 1.9 s, unvoiced (noise only), 'oo'-shaped (low formants), rising then
    falling, gently fluttering."""
    d = 1.9
    n = N(d)
    t = np.arange(n) / SR
    y = _formant_noise(rng, n, [(320, 1.0), (800, 0.6), (2300, 0.2)], 0.35) + 0.15 * hp(white(n, rng), 3000, 2)
    env = np.minimum(t / 0.18, 1) ** 1.5 * np.exp(-np.maximum(t - 0.5, 0) / 0.8)
    env *= 1 + 0.12 * np.sin(2 * np.pi * 7 * t) * np.exp(-t)
    y = lp(y * env, 3500, 2)
    return norm(pan(y, 0.0), db2a(-3)), "synth: unvoiced 'oo' breath: white noise through formant band-passes 320/800/2300 Hz + a little HP 3 kHz air, 0.18 s rise, 0.8 s decay, 7 Hz flutter, LP 3.5 kHz; 1.9 s"


def s_sleeve_wind(rng):
    """The wind / the mist rolling across the egg like a water sleeve: one slow soft gust with a silk swish in it, L->R."""
    d = 2.6
    n = N(d)
    t = np.arange(n) / SR
    base = lp(pink(n, rng), 900, 2)
    sw = bp(white(n, rng), 900, 3500, 2) * np.exp(-((t - 1.0) / 0.35) ** 2) * 0.5
    env = np.sin(np.pi * np.clip(t / d, 0, 1)) ** 1.6
    y = (base + sw) * env
    return norm(pan(y, np.linspace(-0.5, 0.5, n)), db2a(-3)), "synth: pink noise LP 900 Hz gust (sin^1.6 envelope) + a BP 0.9-3.5 kHz silk swish peaking at 1.0 s, panned L->R; 2.6 s"


def s_whisper(rng):
    """Whisper bed: breath close to an ear: unvoiced noise through formant filters that wander every 120-260 ms, with soft
    sibilant puffs. Formants are random and never form a phoneme sequence: no intelligible words by construction."""
    d = 1.6
    n = N(d)
    t = np.arange(n) / SR
    y = np.zeros(n)
    i = 0
    while i < n:
        seg = N(rng.uniform(0.12, 0.26))
        f1, f2 = rng.uniform(350, 700), rng.uniform(1100, 2000)
        w = white(seg + N(0.04), rng)
        s = bp(w, f1 * 0.7, f1 * 1.3, 2) + 0.6 * bp(w, f2 * 0.8, f2 * 1.2, 2)
        e = np.sin(np.pi * np.linspace(0, 1, len(s))) ** 2
        k = min(len(s), n - i)
        y[i:i + k] += (s * e)[:k]
        i += seg
    sib = hp(white(n, rng), 4500, 2) * (np.sin(2 * np.pi * 2.3 * t) > 0.85) * 0.25
    y = (y + lp(sib, 9000, 2)) * np.sin(np.pi * t / d) ** 0.7
    return norm(pan(y, -0.15), db2a(-3)), "synth: unvoiced noise through random wandering formant pairs (F1 350-700, F2 1100-2000 Hz, 120-260 ms each), sparse soft sibilant puffs (HP 4.5 kHz); no phonemes, no words; 1.6 s"


def s_whoosh(rng, d=0.55, lo=250, hi=2600, name=""):
    n = N(d)
    t = np.arange(n) / SR
    x = t / d
    env = np.sin(np.pi * x) ** 2 * (0.3 + 0.7 * x)
    w = white(n, rng)
    # crossfade 4 bands upward with the swing
    bands = np.geomspace(lo, hi, 5)
    y = np.zeros(n)
    for j in range(4):
        b = bp(w, bands[j], bands[j + 1], 2)
        c = np.exp(-((x - (0.2 + 0.2 * j)) / 0.22) ** 2)
        y += b * c
    return y * env


def s_staff_whoosh(rng):
    y = np.concatenate([s_whoosh(rng, 0.42, 220, 2400), np.zeros(N(0.03)), s_whoosh(rng, 0.42, 220, 2400) * 0.8])
    return norm(pan(y, np.linspace(-0.35, 0.35, len(y))), db2a(-3)), "synth: two staff swings (0.42 s each): white noise crossfaded through 4 bands rising 220 -> 2400 Hz with the swing, sin^2 envelope leaning late, panned across"


def s_streetlight(rng):
    """A streetlight pole passing the car window: a short low pressure 'whum' (LP sweep up then down), 0.6 s."""
    d = 0.6
    n = N(d)
    t = np.arange(n) / SR
    x = t / d
    w = pink(n, rng)
    # time-varying LP via crossfade of two low-passes
    a, b = lp(w, 300, 2), lp(w, 1400, 2)
    k = np.exp(-((x - 0.5) / 0.18) ** 2)
    y = (a * (1 - k) + b * k) * np.exp(-((x - 0.5) / 0.22) ** 2)
    return norm(pan(y, np.linspace(0.6, -0.2, n)), db2a(-3)), "synth: pink noise, low-pass crossfading 300 -> 1400 -> 300 Hz around the pass, gaussian swell (0.6 s), panned R -> centre (the pole passes the daughter's window)"


