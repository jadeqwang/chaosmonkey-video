def build_gen(name):
    take, hpf, lpf, gdb, ratio, note = GEN_SOURCES[name]
    y = load(os.path.join(GEN, take + ".mp3"))
    y = lp(hp(y, hpf, 4), lpf, 4)
    if ratio != 1.0:
        y = repitch(y, ratio)
    if gdb is not None:
        y = gate(y, gdb)
    y = norm(y, db2a(-1.0))
    how = (f"generated: media/sound/sfx/gen/{take}.mp3 (elevenlabs/music-v2, prompt in gen/{take}.txt); cleaned: HP {hpf} Hz, "
           f"LP {lpf} Hz" + (f", re-pitched x{ratio}" if ratio != 1 else "") + (f", gate {gdb} dB re peak" if gdb else "") +
           ", normalised to -1 dBFS peak. Content: " + note)
    return y, how


