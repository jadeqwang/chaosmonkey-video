#!/usr/bin/env python3
"""docs/shots_src.yaml -> docs/shots.json (+ docs/shots_report.md).

Every cut-in comes FROM its anchor, resolved in analysis/timing.json; the typed number in the source is only checked
against it. Anything that disagrees (typed vs anchor > 1 frame) or has nothing to cut on within a frame of the typed time
is listed in the report and on stdout; the build does not silently pick something else.

    .venv/bin/python tools/edit/build_shots.py            # writes docs/shots.json and docs/shots_report.md
    .venv/bin/python tools/edit/build_shots.py --dry-run  # report only
"""
import argparse
import json
import sys

import yaml

from common import (FPS, ONE_FRAME, ROOT, SHOTS, SHOTS_SRC, AnchorError, frame_of, load_timing, nearest_points,
                    parse_anchor, resolve_anchor, sync_points, tc)

REPORT = ROOT / 'docs' / 'shots_report.md'


def build(src, timing):
    shots_src = src['shots']
    errors, rows = [], []
    lb_anchor = resolve_anchor(parse_anchor(src['letterbox_until'], timing), timing)
    lb_frame = frame_of(lb_anchor['t'])
    end_t, end_frames = float(src['end']['t']), int(src['end']['frames'])
    pts = sync_points(timing)

    recs = []
    for s in shots_src:
        typed_s, _, spec = str(s['cut']).partition('@')
        try:
            typed = float(typed_s)
            a = resolve_anchor(parse_anchor(spec.strip(), timing), timing)
        except (AnchorError, ValueError) as e:
            errors.append(f'{s["id"]}: {e}')
            continue
        recs.append((s, typed, spec.strip(), a))
    if errors:
        return None, errors, None, None

    shots = []
    for i, (s, typed, spec, a) in enumerate(recs):
        nxt = recs[i + 1] if i + 1 < len(recs) else None
        in_f = frame_of(a['t'])
        out_f = frame_of(nxt[3]['t']) if nxt else end_frames
        out_t = nxt[3]['t'] if nxt else end_t
        sec = src['sections'][s['section'] if 'section' in s else s['id'][0]]
        ph = s.get('phase')
        shots.append({
            'id': s['id'],
            'section': s.get('section', s['id'][0]),
            'section_title': sec['title'],
            'in': a['t'], 'out': out_t,
            'in_frame': in_f, 'out_frame': out_f, 'frames': out_f - in_f,
            'in_tc': tc(in_f), 'out_tc': tc(out_f),
            'typed_in': typed,
            'anchor': a,
            'anchor_spec': spec,
            'anchor_text': s.get('anchor_text'),
            'picture': s.get('picture', ''),
            'staging': s.get('staging', ''),
            'dir': s.get('dir'),
            'sun': s.get('sun'),
            'mirrors': s.get('mirrors', []) or [],
            'phase': ph,
            'phase_label': src['phases'][ph]['label'] if ph else None,
            'letterbox': in_f < lb_frame,
        })
        # the report: typed time vs the anchor, and is there anything at all to cut on near the typed time?
        d = typed - a['t']
        near = nearest_points(typed, pts, ONE_FRAME)
        flag = []
        if abs(d) > ONE_FRAME + 1e-9:
            flag.append('typed vs anchor > 1 frame')
        elif frame_of(typed) != in_f and abs(d) > 0.010:
            # (typed numbers are rounded to 0.01 s, so a frame change from <= 10 ms of rounding is not reported)
            flag.append('within a frame, but the cut frame moves')
        if not near:
            flag.append('nothing to cut on within a frame of the typed time')
        rows.append(dict(soft=a.get('soft'), id=s['id'], typed=typed, anchor=a, d=d, in_f=in_f, typed_f=frame_of(typed), near=near, flag=flag))
    meta = {
        'fps': FPS, 'frame_rule': 'ceil(t*24)', 'end_t': end_t, 'total_frames': end_frames,
        'letterbox_until': {'anchor': lb_anchor, 'frame': lb_frame},
        'source': 'docs/shots_src.yaml', 'timing': 'analysis/timing.json',
        'phases': src['phases'], 'sections': src['sections'],
    }
    return {'meta': meta, 'shots': shots}, errors, rows, pts


def report(rows, pts):
    out = ['# Shot build report', '',
           'Generated by `tools/edit/build_shots.py` from `docs/shots_src.yaml`. Cut times come from the anchors; this lists '
           'where the typed time in the shot list disagrees with its anchor (> 1 frame = 41.7 ms), where the frame moves '
           'even though they agree within a frame, where there is nothing (beat, word, event) within a frame of the typed '
           'time, and soft anchors. Frame = ceil(t*24).', '',
           '| Shot | Typed | Anchor | Anchor t | Δ ms | Frame typed→anchor | Flags | Within a frame of the typed time |',
           '|---|---|---|---|---|---|---|---|']
    n = 0
    for r in rows:
        if not r['flag']:
            continue
        n += 1
        near = ', '.join(f'{lab} {t:.3f}' for t, lab in r['near'][:4]) or '—'
        out.append(f'| {r["id"]} | {r["typed"]:.2f} | {r["anchor"]["label"]} | {r["anchor"]["t"]:.3f} | '
                   f'{r["d"]*1000:+.0f} | {r["typed_f"]}→{r["in_f"]} | {"; ".join(r["flag"])} | {near} |')
    if n == 0:
        out.append('| — | | | | | | nothing to report | |')
    soft = [r for r in rows if r['soft']]
    out += ['', '## Soft anchors (for information)', '',
            'Anchors timing.json itself marks as uncertain: interpolated beats/downbeats (no onset; may be ±40 ms off what a '
            'listener taps), medium/soft word onsets, section boundaries.', '',
            '| Shot | Anchor | t | Why soft |', '|---|---|---|---|']
    out += [f'| {r["id"]} | {r["anchor"]["label"]} | {r["anchor"]["t"]:.3f} | {r["soft"]} |' for r in soft]
    return '\n'.join(out) + '\n', n


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--src', default=str(SHOTS_SRC))
    ap.add_argument('--out', default=str(SHOTS))
    ap.add_argument('--dry-run', action='store_true')
    args = ap.parse_args()
    src = yaml.safe_load(open(args.src))
    timing = load_timing()
    data, errors, rows, pts = build(src, timing)
    if errors:
        print('ANCHOR ERRORS (nothing written):')
        for e in errors:
            print('  ' + e)
        sys.exit(2)
    md, n = report(rows, pts)
    # stdout: the flagged rows only
    print(f'{len(data["shots"])} shots, frames 0..{data["meta"]["total_frames"] - 1}, letterbox until frame '
          f'{data["meta"]["letterbox_until"]["frame"]}')
    for r in rows:
        if r['flag']:
            print(f'  {r["id"]:4s} typed {r["typed"]:7.2f}  anchor {r["anchor"]["label"]:28s} {r["anchor"]["t"]:8.3f}  '
                  f'Δ {r["d"]*1000:+5.0f} ms  frame {r["typed_f"]}->{r["in_f"]}  | {"; ".join(r["flag"])}')
    if args.dry_run:
        return
    tmp = args.out + '.partial'
    with open(tmp, 'w') as fh:
        json.dump(data, fh, indent=1, ensure_ascii=False)
        fh.write('\n')
    import os
    os.replace(tmp, args.out)
    REPORT.write_text(md)
    print(f'wrote {args.out} and {REPORT.relative_to(ROOT)} ({n} flagged)')


if __name__ == '__main__':
    main()
