import os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
PY = sys.executable
CFG = 'work/swarm/C/comp_D.json'
SPLITS = {'F4': (0, 83), 'F5': (83, 43), 'F6a': (126, 50)}


def split(frames, suffix=''):
    for name, (a, n) in SPLITS.items():
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-framerate', '24', '-start_number', str(a), '-i', f'{frames}/f%04d.png', '-frames:v', str(n),
                        '-an', '-c:v', 'libx264', '-preset', 'slow', '-crf', '14', '-pix_fmt', 'yuv420p', '-r', '24', '-movflags', '+faststart',
                        f'media/comp/{name}{suffix}.mp4'], check=True)


if __name__ == '__main__':
    subprocess.run([PY, 'tools/swarm4/vcomp.py', CFG], check=True)
    subprocess.run(['cp', 'media/comp/F4F5F6a_D.mp4', 'media/comp/F4F5F6a.mp4'], check=True)
    split('work/swarm/D/frames')
    if '--master' in sys.argv:
        subprocess.run([PY, 'tools/swarm4/vcomp.py', CFG, '--w', '1920', '--h', '1080'], check=True)
